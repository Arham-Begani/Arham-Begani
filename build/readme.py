"""Assembles README.md around the generated graphics."""
from __future__ import annotations

from .config import Config
from .github import Stats

CACHE_BUST = True

COLOPHON = """Every graphic on this page is generated here, not borrowed from a third-party
badge service. `portrait.svg` is a photo pushed through a character ramp; the stat
block, the language bars and the year grid are drawn straight from the GitHub
GraphQL API by a scheduled action, once a day, committing only what changed.

They animate with SMIL from inside the SVG, because GitHub renders README images
with scripting disabled — and since nothing loads from anyone else's domain,
nothing here can rate-limit or go dark. The section headings are SVGs for the
same reason: GitHub strips CSS from READMEs, so an image is the only way to put
this page's own typeface on them.

Source is in this repo. Take it if you want it."""


def _pic(name: str, ver: dict[str, str], alt: str, *, width: str = "") -> str:
    """A theme-aware image pair.

    GitHub has supported <picture> + prefers-color-scheme in Markdown since
    2022, so this is the supported way to ship a dark and a light rendering.
    The ?v= is a cache-buster: the URL only changes when the drawing does,
    which is what nudges GitHub's image proxy to re-fetch on the day you ship.
    """
    def src(theme: str) -> str:
        v = ver.get(f"{name}-{theme}", "")
        return f"out/{name}-{theme}.svg" + (f"?v={v}" if v and CACHE_BUST else "")
    w = f' width="{width}"' if width else ""
    return (
        "<picture>\n"
        f'  <source media="(prefers-color-scheme: dark)" srcset="{src("dark")}">\n'
        f'  <img alt="{alt}" src="{src("light")}"{w}>\n'
        "</picture>"
    )


def build(cfg: Config, s: Stats, ver: dict[str, str]) -> str:
    p: list[str] = []
    p.append("<!-- Generated by generate.py. Edit profile.toml, not this file. -->")
    p.append(f'<div align="center">\n\n{_pic("portrait", ver, f"{cfg.name or cfg.username}", width="460")}\n\n</div>')
    p.append(_pic("hero", ver, f"{s.total} contributions in the last year"))

    if cfg.links:
        p.append('<p align="center">' +
                 " &nbsp;·&nbsp; ".join(f'<a href="{l.url}">{l.label}</a>' for l in cfg.links) +
                 "</p>")

    if cfg.about:
        p.append(_pic("h-about", ver, "about"))
        p.append("\n\n".join(cfg.about))

    if cfg.stack:
        p.append(_pic("h-stack", ver, "stack"))
        p.append(_pic("stack", ver, ", ".join(cfg.stack)))

    if cfg.projects:
        p.append(_pic("h-projects", ver, "projects"))
        rows = []
        for pr in cfg.projects:
            name = f"**[{pr.name}]({pr.url})**" if pr.url else f"**{pr.name}**"
            head = f"{name} · {pr.meta}" if pr.meta else name
            rows.append(f"{head}  \n{pr.blurb}")
        p.append("\n\n".join(rows))

    p.append(_pic("h-stats", ver, "stats"))
    p.append(_pic("stats", ver, "language and repository stats"))
    p.append(_pic("heatmap", ver, f"{s.active_days} active days in the last year"))

    if cfg.colophon:
        p.append(_pic("h-colophon", ver, "about this page"))
        p.append(COLOPHON)

    return "\n\n".join(p) + "\n"
